import assert from 'node:assert/strict';
import {initializeSpline,wakeSplineInitializations} from '../app/components/experience/spline-initialization.ts';
const scheduled=[];
globalThis.scheduler={postTask:async task=>{scheduled.push(task);}};
const drain=async()=>{await new Promise(setImmediate);while(scheduled.length){scheduled.shift()();await new Promise(setImmediate);}};
const events=[];
let release,visible=false;
const first=initializeSpline(()=>new Promise(resolve=>{events.push('first');release=resolve;}),new AbortController().signal,()=>true);
const hidden=initializeSpline(async()=>{events.push('hidden');},new AbortController().signal,()=>visible);
const last=initializeSpline(async()=>{events.push('last');},new AbortController().signal,()=>true);
const cancelled=new AbortController();
const removed=initializeSpline(async()=>{throw Error('cancelled job ran');},cancelled.signal,()=>true).catch(e=>e);
cancelled.abort();
await drain();assert.deepEqual(events,['first'],'only one context initializes at once');
release();await first;await drain();await last;
assert.deepEqual(events,['first','last'],'hidden jobs do not block visible jobs');
visible=true;wakeSplineInitializations();await drain();await hidden;
assert.deepEqual(events,['first','last','hidden']);
assert.equal((await removed).name,'AbortError');
const failed=initializeSpline(async()=>{throw Error('load failed');},new AbortController().signal,()=>true).catch(e=>e.message);
const recovered=initializeSpline(async()=>{events.push('recovered');},new AbortController().signal,()=>true);
await drain();assert.equal(await failed,'load failed');await recovered;
assert.equal(events.at(-1),'recovered','failure releases the initialization slot');
console.log('PASS: serialization, visibility, cancellation, failure recovery.');
